"""Run the acceptance circuits and examples through the real runner and save
{code, response} JSON fixtures for the frontend (lib/circuit/__fixtures__).

    pnpm fixtures      (or: cd runner && uv run python scripts/export_fixtures.py)
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from qrunner import run_code  # noqa: E402

OUT = ROOT.parent / "lib" / "circuit" / "__fixtures__"
SOURCES = sorted([*(ROOT / "tests" / "circuits").glob("*.py"), *(ROOT / "examples").glob("*.py")])
DEFAULT = """import pennylane as qml
from pennylane import numpy as np

dev = qml.device("default.qubit", wires=2)


@qml.set_shots(1000)
@qml.qnode(dev)
def bell():
    qml.Hadamard(wires=0)
    qml.CNOT(wires=[0, 1])
    return qml.counts()


print(bell())
"""
ERRORS = {
    "e1_syntax": "import pennylane as qml\n\ndev = qml.device(\"default.qubit\", wires=2)\n\n@qml.qnode(dev)\ndef bell():\n    qml.Hadamard(wires=0\n    qml.CNOT(wires=[0, 1])\n    return qml.probs()\n\nbell()\n",
    "e2_wire": "import pennylane as qml\n\ndev = qml.device(\"default.qubit\", wires=2)\n\n@qml.qnode(dev)\ndef bell():\n    qml.Hadamard(wires=0)\n    qml.CNOT(wires=[0, 2])\n    return qml.probs()\n\nbell()\n",
}


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    items = [("00_default", DEFAULT)] + [(p.stem, p.read_text(encoding="utf-8")) for p in SOURCES] + list(ERRORS.items())
    for name, code in items:
        response = run_code(code)
        response["durationMs"] = 0  # keep fixtures stable
        (OUT / f"{name}.json").write_text(json.dumps({"name": name, "code": code, "response": response}, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
        status = "ok" if response["ok"] else f"error {response['error']['kind']}"
        print(f"{name:22} {status}")
    write_index([name for name, _ in items])


def write_index(names: list[str]) -> None:
    lines = ["// Generated by runner/scripts/export_fixtures.py: do not edit.", 'import type { Fixture } from "./types";']
    lines += [f'import f{i} from "./__fixtures__/{n}.json";' for i, n in enumerate(names)]
    lines += ["", "export const FIXTURES: Record<string, Fixture> = {"]
    lines += [f'  "{n}": f{i} as unknown as Fixture,' for i, n in enumerate(names)]
    lines += ["};", "", 'export const DEFAULT_FIXTURE = "00_default";', ""]
    (OUT.parent / "fixtures.ts").write_text("\n".join(lines), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
